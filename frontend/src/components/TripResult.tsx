"use client";

import { useState } from "react";
import { AlertTriangle, Calendar, Users, Wallet } from "lucide-react";
import type { GenerateResponse } from "@/lib/trip-schema";
import { formatDay, formatINR, shortPlaceName } from "@/lib/format";
import { ItineraryView } from "@/components/ItineraryView";
import { MapPanel } from "@/components/MapPanel";
import { BudgetView } from "@/components/BudgetView";
import { WeatherView } from "@/components/WeatherView";
import { SaveTripButton } from "@/components/SaveTripButton";

const TABS = [
  { id: "itinerary", label: "Itinerary" },
  { id: "map", label: "Map" },
  { id: "budget", label: "Budget" },
  { id: "weather", label: "Weather" },
] as const;

type TabId = (typeof TABS)[number]["id"];

export function TripResult({ result, showSave = true }: { result: GenerateResponse; showSave?: boolean }) {
  const [tab, setTab] = useState<TabId>("itinerary");
  const req = result.request;
  const title = result.destination ? shortPlaceName(result.destination.display_name) : req.destination;

  return (
    <section className="space-y-5" aria-label="Your trip plan">
      <header className="flex flex-wrap items-end justify-between gap-4">
        <div>
          <h2 className="text-2xl font-bold text-slate-900 sm:text-3xl">{title}</h2>
          {result.destination && (
            <p className="mt-0.5 text-sm text-slate-500">Planned for: {result.destination.display_name}</p>
          )}
          <div className="mt-2 flex flex-wrap gap-2 text-sm text-slate-700">
            <span className="inline-flex items-center gap-1.5 rounded-full bg-white px-3 py-1 ring-1 ring-slate-200">
              <Calendar className="h-4 w-4 text-teal-600" aria-hidden />
              {formatDay(req.start_date)} - {formatDay(req.end_date)}
            </span>
            <span className="inline-flex items-center gap-1.5 rounded-full bg-white px-3 py-1 ring-1 ring-slate-200">
              <Users className="h-4 w-4 text-teal-600" aria-hidden />
              {req.travelers} traveller{req.travelers > 1 ? "s" : ""}
            </span>
            <span className="inline-flex items-center gap-1.5 rounded-full bg-white px-3 py-1 ring-1 ring-slate-200">
              <Wallet className="h-4 w-4 text-teal-600" aria-hidden />
              {formatINR(req.budget)}
            </span>
          </div>
        </div>
        {showSave && <SaveTripButton result={result} />}
      </header>

      {result.warnings.length > 0 && (
        <ul className="space-y-2">
          {result.warnings.map((w, i) => (
            <li key={i} className="flex items-start gap-2 rounded-xl border border-amber-200 bg-amber-50 p-3 text-sm text-amber-900">
              <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0" aria-hidden />
              {w}
            </li>
          ))}
        </ul>
      )}

      <div className="flex gap-1 overflow-x-auto border-b border-slate-200" role="tablist">
        {TABS.map((t) => (
          <button
            key={t.id}
            role="tab"
            aria-selected={tab === t.id}
            onClick={() => setTab(t.id)}
            className={`-mb-px shrink-0 border-b-2 px-4 py-2.5 text-sm font-semibold transition-colors ${
              tab === t.id ? "border-teal-600 text-teal-700" : "border-transparent text-slate-500 hover:text-slate-800"
            }`}
          >
            {t.label}
          </button>
        ))}
      </div>

      <div role="tabpanel">
        {tab === "itinerary" && <ItineraryView result={result} />}
        {tab === "map" && <MapPanel result={result} />}
        {tab === "budget" && <BudgetView budget={result.budget} travelers={req.travelers} />}
        {tab === "weather" && <WeatherView weather={result.weather} />}
      </div>

      <p className="text-xs text-slate-500">
        Generated by {result.model.replace(":", " / ")}. Costs are estimates, not booking prices.
      </p>
    </section>
  );
}
